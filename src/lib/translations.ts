export function translateText(text: string, locale: Locale): string {
  const leadingWhitespace = text.match(/^\s*/)?.[0] ?? "";
  const trailingWhitespace = text.match(/\s*$/)?.[0] ?? "";
  const trimmedText = text.trim();
  if (!trimmedText) return text;
  const normalizedText = normalizeText(trimmedText);
  const serviceTranslation = localizedServiceContent.get(normalizedText);
  const legacyTranslation = legacyIndonesianContent.get(normalizedText);
  const translatedText =
    locale === "en"
      ? serviceTranslation?.en ??
        indonesianToEnglish.get(normalizedText) ??
        legacyTranslation?.en ??
        trimmedText
      : normalizedTranslations.get(normalizedText) ??
        serviceTranslation?.id ??
        legacyTranslation?.id ??
        trimmedText;

  return `${leadingWhitespace}${translatedText}${trailingWhitespace}`;
}

